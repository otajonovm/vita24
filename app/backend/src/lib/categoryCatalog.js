function isJunkCategory(category) {
  if (!category) return true;
  const slug = String(category.slug || "").toLowerCase();
  const name = String(category.name || "").trim().toLowerCase();
  if (JUNK_CATEGORY_SLUGS.has(slug)) return true;
  if (slug.startsWith("lekko")) return true;
  if (JUNK_CATEGORY_NAMES.has(name)) return true;
  if (/^(крем|мазь|гель|сироп|капли|таб\.?|капс\.?|супп\.?|р-р|спрей)$/i.test(name)) return true;
  return false;
}

